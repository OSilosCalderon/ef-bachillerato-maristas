type RecipeWeights = Partial<Record<keyof typeof ingredientIds, number>>;

// Gramos de cada componente en 100 g de una preparación orientativa servida.
// Se reutilizan las fichas del catálogo para calcular el aporte de cada ración.
function recipe(id: string, name: string, aliases: string[], weights: RecipeWeights): CatalogRecipe {
  return {
    id, name, aliases, unit: "g",
    ingredients: Object.entries(weights).map(([ingredient, grams]) => ({
      ingredientId: ingredientIds[ingredient as keyof typeof ingredientIds], share: grams / 100,
    })),
  };
}

