const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const ts = require("typescript");

const source = fs.readFileSync(path.join(__dirname, "../lib/sa4-event.ts"), "utf8");
const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const exported = {};
new Function("exports", code)(exported);
const { eventMatches, matchWinner, leagueStandings, emptyStep, projectSteps, validateStep, delegationStandings, validateLogoRanking, logoStandings, mergeLogoUpdates } = exported;
const countries = ["DO", "ES", "JM", "MX", "GR", "BR", "JP", "IT"];
const league = eventMatches("league", countries);
assert.equal(league.length, 28);
assert.equal(new Set(league.map(({ a, b }) => [a, b].sort().join("-"))).size, 28);
for (const country of countries) assert.equal(league.filter((match) => match.a === country || match.b === country).length, 7);
assert.equal(eventMatches("league", ["DO", "DO"]).length, 0);
const first = league[0];
const next = league[1];
const scores = { [first.id]: { a: 0, b: 2 }, [next.id]: { a: 0, b: 0 } };
const table = leagueStandings(countries, league, scores);
assert.equal(table.find((row) => row.country === first.b).points, 3);
assert.equal(table.find((row) => row.country === first.a).points, 0);
assert.equal(table.find((row) => row.country === next.a).points, 1);
assert.equal(table.find((row) => row.country === next.b).drawn, 1);
assert.equal(table.reduce((sum, row) => sum + row.played, 0), 4);

const quarter = eventMatches("knockout", countries)[0];
assert.equal(matchWinner(quarter, { a: 1, b: 1 }), null);
assert.equal(matchWinner(quarter, { a: 1, b: 1, winner: quarter.a }), quarter.a);
assert.equal(matchWinner(quarter, { a: 1, b: 1, winner: "JP" }), null);
const playoffScores = { q0: { a: 1, b: 0 }, q1: { a: 2, b: 3 }, q2: { a: 0, b: 1 }, q3: { a: 4, b: 1 }, s0: { a: 0, b: 2 }, s1: { a: 2, b: 2, winner: "BR" } };
const knockout = eventMatches("knockout", countries, playoffScores);
assert.equal(knockout.length, 7);
assert.deepEqual([knockout[4].a, knockout[4].b], ["DO", "MX"]);
assert.deepEqual([knockout[6].a, knockout[6].b], ["MX", "BR"]);
assert.equal(matchWinner(knockout[6], { a: 3, b: 2 }), "MX");

const draft = emptyStep("competition", countries);
validateStep("competition", draft, countries);
assert.throws(() => validateStep("competition", { ...draft, order: Array(8).fill("DO") }, countries));
assert.throws(() => validateStep("results", { scores: { q0: { a: -1, b: 0 } } }, countries));
assert.throws(() => validateStep("results", { scores: { q0: { a: 1.2, b: 0 } } }, countries));
validateStep("results", { scores: { q0: { a: 0, b: null } } }, countries);
assert.throws(() => validateStep("identity", { name: "", slogan: "", meaning: "", logo: "data:image/svg+xml;base64,AAAA" }, countries));
const partialProject = { country_code: "DO", content: { sport: { sport: "Baloncesto" }, _revisions: { sport: 3 }, legacy: { text: "saved" } }, updated_at: "2026-11-23" };
const steps = projectSteps([partialProject]);
assert.equal(steps.length, 1);
assert.equal(steps[0].revision, 3);
assert.deepEqual(partialProject.content.legacy, { text: "saved" });
const ranking = Object.fromEntries(countries.map((country, index) => [country, index + 1]));
assert.deepEqual(validateLogoRanking(ranking, countries), ranking);
assert.throws(() => validateLogoRanking({ ...ranking, ES: 1 }, countries));
assert.throws(() => validateLogoRanking({ ...ranking, ES: "2" }, countries));
assert.throws(() => validateLogoRanking({ ...ranking, IT: 9 }, countries));
assert.throws(() => validateLogoRanking({ ...ranking, IT: 2.5 }, countries));
assert.throws(() => validateLogoRanking({ ...ranking, EXTRA: 8 }, countries));
assert.throws(() => validateLogoRanking(Object.fromEntries(Object.entries(ranking).filter(([code]) => code !== "IT")), countries));
assert.throws(() => validateLogoRanking({ ...Object.fromEntries(countries.slice(0, 7).map((country, i) => [country, i + 1])), XX: 8 }, countries));
const reverse = Object.fromEntries(countries.map((country, index) => [country, 8 - index]));
const logos = logoStandings(countries, [{ scores: ranking }, { scores: reverse }]);
assert.ok(logos.every((row) => row.points === 9 && row.ratings === 2));
assert.equal(logos.reduce((sum, row) => sum + row.points, 0), 72);

const delegations = countries.map((country_code, position) => ({ country_code, country: country_code, position, members: [] }));
const section = (country_code, step, data) => ({ country_code, step, data, revision: 1, updated_at: "2026-11-23" });
let overall = delegationStandings(delegations, []);
assert.equal(overall.completed, 0);
assert.ok(overall.rows.every((row) => row.points === 0 && row.position === null));
const competition = section("DO", "competition", { ...draft, format: "league" });
const allDraws = Object.fromEntries(league.map((match) => [match.id, { a: 0, b: 0 }]));
overall = delegationStandings(delegations, [competition, section("DO", "results", { scores })]);
assert.equal(overall.completed, 0, "Partial activities must not award points");
overall = delegationStandings(delegations, [competition, section("DO", "results", { scores: allDraws })]);
assert.equal(overall.completed, 1);
assert.ok(overall.rows.every((row) => row.points === 9 && row.position === 1));
assert.equal(overall.rows.reduce((sum, row) => sum + row.points, 0), 72);
// Deterministic league with eight distinct positions; input order must not change ranking.
const orderedScores = Object.fromEntries(league.map((match) => [match.id, { a: countries.indexOf(match.a) < countries.indexOf(match.b) ? 1 : 0, b: countries.indexOf(match.a) < countries.indexOf(match.b) ? 0 : 1 }]));
const fullLeague = [competition, section("DO", "results", { scores: orderedScores })];
overall = delegationStandings(delegations.toReversed(), fullLeague);
assert.deepEqual(overall.rows.map((row) => row.country), countries);
assert.deepEqual(overall.rows.map((row) => row.points), [16, 14, 12, 10, 8, 6, 4, 2]);
const knockoutConfig = section("ES", "competition", { ...draft, format: "knockout" });
const fullKnockout = [knockoutConfig, section("ES", "results", { scores: { ...playoffScores, final: { a: 3, b: 2 } } })];
overall = delegationStandings(delegations, fullKnockout);
assert.equal(overall.completed, 1);
assert.equal(overall.rows.find((row) => row.country === "MX").points, 16);
assert.equal(overall.rows.find((row) => row.country === "BR").points, 14);
assert.equal(overall.rows.filter((row) => row.points === 11).length, 2);
assert.equal(overall.rows.filter((row) => row.points === 5).length, 4);
assert.equal(overall.rows.reduce((sum, row) => sum + row.points, 0), 72);
overall = delegationStandings(delegations, [knockoutConfig, section("ES", "results", { scores: { ...playoffScores, final: { a: 0, b: 0 } } })]);
assert.equal(overall.completed, 0, "An unresolved knockout tie must remain pending");
overall = delegationStandings(delegations, [...fullLeague, ...fullKnockout]);
assert.equal(overall.completed, 2);
assert.equal(overall.rows.find((row) => row.country === "MX").points, 26);
assert.equal(overall.rows.reduce((sum, row) => sum + row.points, 0), 144);
const eightSports = countries.flatMap((country) => fullLeague.map((row) => ({ ...row, country_code: country })));
overall = delegationStandings(delegations, eightSports);
assert.equal(overall.completed, 8);
assert.equal(overall.rows[0].points, 128);
assert.equal(overall.rows.reduce((sum, row) => sum + row.points, 0), 576);
// A logo saved by another delegation must replace its old preview without losing a vote or another step.
const oldIdentity = section("ES", "identity", { name: "Antes", logo: "", slogan: "", meaning: "" });
const nextIdentity = section("ES", "identity", { name: "Nueva propuesta", logo: "data:image/png;base64,AAAA", slogan: "Participar", meaning: "Ocho equipos" });
const sharedWorkspace = { steps: [oldIdentity, ...fullLeague], projectVersions: { ES: "before", DO: "same" }, phase: "voting", ownVote: ranking, votes: [{ scores: ranking }] };
const refreshed = mergeLogoUpdates(sharedWorkspace, { countries: ["ES"], steps: [nextIdentity], versions: { ES: "after" } });
assert.equal(refreshed.steps.filter(row => row.country_code === "ES" && row.step === "identity").length, 1);
assert.equal(refreshed.steps.find(row => row.country_code === "ES" && row.step === "identity").data.logo, nextIdentity.data.logo);
assert.equal(refreshed.steps.find(row => row.step === "results"), fullLeague[1]);
assert.equal(refreshed.ownVote, sharedWorkspace.ownVote);
assert.equal(refreshed.votes, sharedWorkspace.votes);
assert.equal(refreshed.phase, "voting");
assert.deepEqual(refreshed.projectVersions, { ES: "after", DO: "same" });
console.log("SA4: match coverage, knockout tiebreaks, preserved projects, complete 1–8 logo ballots, equal points per sport, tied places and eight-sport totals passed.");
console.log("SA4 logos: refreshed proposals preserve votes, competition results and other delegations.");
