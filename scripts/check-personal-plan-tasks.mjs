import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
import { webcrypto } from "node:crypto";
import ts from "typescript";

const module = { exports: {} };
vm.runInNewContext(ts.transpileModule(fs.readFileSync("lib/personal-plan-tasks.ts", "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { module, exports: module.exports, crypto: webcrypto });
const { normalizeItems, cleanPlanItems, emptyExercise, copyPlanItemToSession } = module.exports;
const legacy = { id: "old", activity: "Carrera", exerciseId: "continuous", sessionDate: "2026-10-13", day: "Martes", goal: "2", capacity: "resistencia", dose: "12 min", recovery: "2 min", description: "Ritmo regular" };
const migrated = normalizeItems([legacy]);
assert.equal(migrated.length, 1);
assert.equal(migrated[0].methodology, "custom");
assert.equal(migrated[0].sessionDate, legacy.sessionDate);
for (const key of ["exerciseId", "activity", "capacity", "dose", "recovery", "description"]) assert.equal(migrated[0].exercises[0][key], legacy[key]);
const task = { ...migrated[0], methodology: "circuit", rounds: "2", roundRecovery: "90 s", materials: ["Conos", "Balones"], customMaterials: "Petos azules", exercises: [migrated[0].exercises[0], { ...emptyExercise(), activity: "Sentadilla", dose: "8 repeticiones", recovery: "30 s" }, { ...emptyExercise(), activity: "Movilidad", dose: "8 movimientos", recovery: "20 s" }] };
const beforeCopy = JSON.stringify(task);
const target = { date: "2026-10-29", day: "Jueves" };
const copied = copyPlanItemToSession(task, target);
assert.notEqual(copied.id, task.id);
assert.equal(copied.sessionDate, target.date);
assert.equal(copied.day, target.day);
for (const key of ["activity", "goal", "methodology", "rounds", "roundRecovery", "customMaterials"]) assert.equal(copied[key], task[key]);
assert.equal(JSON.stringify(copied.materials), JSON.stringify(task.materials));
assert.notEqual(copied.materials, task.materials);
assert.equal(copied.exercises.length, task.exercises.length);
copied.exercises.forEach((exercise, index) => {
  assert.notEqual(exercise.id, task.exercises[index].id);
  for (const key of ["exerciseId", "activity", "description", "capacity", "dose", "recovery"]) assert.equal(exercise[key], task.exercises[index][key]);
});
assert.equal(JSON.stringify(task), beforeCopy, "Copying must not change the source task.");
copied.exercises[0].dose = "6 min";
copied.materials.push("Colchoneta");
assert.equal(JSON.stringify(task), beforeCopy, "Editing the copy must not affect the source exercises or materials.");
const copiedAgain = copyPlanItemToSession(task, target);
assert.notEqual(copiedAgain.id, copied.id);
assert.notEqual(copiedAgain.exercises[0].id, copied.exercises[0].id);
const destinationTask = { ...task, id: "already-on-destination", sessionDate: target.date, day: target.day };
const copiedPlan = normalizeItems(JSON.parse(JSON.stringify(cleanPlanItems([task, destinationTask, copied], true))));
assert.equal(copiedPlan.length, 3, "Copying to an occupied date adds a task without replacing existing work.");
assert.equal(copiedPlan[0].id, task.id);
assert.equal(copiedPlan[1].id, destinationTask.id);
assert.equal(copiedPlan.filter((item) => item.sessionDate === target.date).length, 2);
assert.equal(copiedPlan[2].exercises[0].dose, "6 min", "Copied exercises survive the existing save/load path.");
console.log("Task copies preserve all training data, use independent IDs and arrays, append to occupied dates and survive save/reload.");

const saved = cleanPlanItems([task, { ...task, id: "same-date" }], true);
const reloaded = normalizeItems(JSON.parse(JSON.stringify(saved)));
assert.equal(JSON.stringify(reloaded), JSON.stringify(saved));
assert.equal(reloaded[0].exercises.length, 3);
assert.deepEqual(Array.from(reloaded[0].materials), ["Conos", "Balones"]);
assert.equal(reloaded[0].customMaterials, "Petos azules");
assert.equal(reloaded[1].sessionDate, reloaded[0].sessionDate);
assert.equal(cleanPlanItems([task], false)[0].goal, "1");
assert.equal(normalizeItems([null, [], 3]).length, 0);
assert.equal(emptyExercise().id === emptyExercise().id, false);
assert.equal(normalizeItems([{ ...task, exercises: [] }])[0].exercises.length, 0);
const planUi = fs.readFileSync("components/second-year-personal-plan.tsx", "utf8");
const taskUi = fs.readFileSync("components/personal-plan-task-editor.tsx", "utf8");
assert.match(planUi, /¿Cómo comprobaré mi objetivo principal\?/);
assert.match(planUi, /Define uno o dos objetivos y la temporalización/);
assert.match(planUi, /title="Descargar el plan visible en formato PDF"/);
assert.doesNotMatch(planUi, /disabled={!form\.objective\.trim\(\) \|\| form\.items\.length === 0}/);
assert.match(planUi, /courseYear === 2 \? 3/);
assert.match(planUi, /courseYear === 2 \? 4/);
assert.match(taskUi, /Series de la tarea completa/);
assert.match(taskUi, /Descanso entre series \(minutos\)/);
assert.match(taskUi, /Materiales para esta tarea/);
assert.match(taskUi, /Otros materiales \(texto libre\)/);
assert.doesNotMatch(taskUi, /Vueltas de la tarea completa|Descanso entre vueltas/);
console.log("Personal plans: legacy data survives save/reload and the SA1 form uses the fixed schedule and series terminology.");
