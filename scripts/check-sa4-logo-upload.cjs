let failDecode=false, revoked=0, canvases=0, fills=0;
const small=(type)=>`data:image/${type};base64,AAAA`;
const large=(type)=>`data:image/${type};base64,${"A".repeat(350000)}`;
const makeCanvas=(encode)=>()=>{
  canvases++;
  const context={drawImage(){},fillRect(){fills++;},globalCompositeOperation:"source-over",fillStyle:""};
  return {width:0,height:0,getContext(){return context;},toDataURL:encode};
};
